def _q(unit, course, kind, difficulty, text, options, correct, ref):
    """الهدف: إنشاء قاموس سؤال موحد. options = قائمة نصوص الخيارات (أو None لصح/خطأ)."""
    return {"unit": unit, "course": course, "kind": kind, "difficulty": difficulty,
            "text": text, "options": options, "correct": correct, "ref": ref}


def mcq(unit, course, difficulty, text, correct, pool, ref):
    """الهدف: سؤال اختيار من متعدد: الصحيح + 3 مشتتات من نفس الوحدة، بترتيب عشوائي."""
    distractors = sorted({str(p) for p in pool if str(p) != str(correct)})
    options = [str(correct)] + RNG.sample(distractors, 3)
    RNG.shuffle(options)
    return _q(unit, course, "اختيار من متعدد", difficulty, text, options, str(correct), ref)


def tf(unit, course, difficulty, text, truth, ref):
    """الهدف: سؤال صح / خطأ."""
    return _q(unit, course, "صح / خطأ", difficulty, text, None, "صح" if truth else "خطأ", ref)


def purpose_questions(unit, table, name_col, purpose_col, label, difficulty="سهل", display=None):
    """الهدف: لكل صف سؤال «ما العنصر الذي هدفه ...؟»."""
    display = display or (lambda r: r[name_col])
    pool = [display(r) for r in table]
    return [mcq(unit, course_of(unit, r[0]), difficulty,
                f"{label}: {r[purpose_col]}؟", display(r), pool, f"{unit} • {r[0]}")
            for r in table]


def output_questions(unit, table, ex_col, out_col, difficulty="متوسط"):
    """الهدف: لكل صف سؤال «ما ناتج تنفيذ ...؟» والمشتتات نواتج صفوف أخرى."""
    pool = [r[out_col] for r in table]
    return [mcq(unit, course_of(unit, r[0]), difficulty, f"ما ناتج تنفيذ: {r[ex_col]}",
                r[out_col], pool, f"{unit} • {r[0]}") for r in table]


