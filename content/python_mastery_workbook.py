    per_unit = {}
    for c in FLASHCARDS:
        per_unit[c[1]] = per_unit.get(c[1], 0) + 1
    days = {}
    for _, s, _ in PLAN_RAW:
        days[s] = days.get(s, 0) + 1
    seen, rows = {}, []
    for d, (topic, s, quiz) in enumerate(PLAN_RAW, start=1):
        total, n = per_unit.get(s, 0), days[s]
        k = seen.get(s, 0)
        seen[s] = k + 1
        share = (total // n + (1 if k < total % n else 0)) if total else 0
        rows.append([f"اليوم {d}", topic, s, share, quiz, None])
    return rows


