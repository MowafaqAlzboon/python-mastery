    h = ws.cell(row=hr, column=1, value="طريقة استخدام الملف")
    h.font = Font(bold=True, color="FFFFFF", size=12)
    h.fill = PatternFill("solid", fgColor=DARK_BLUE)
    h.alignment = Alignment(horizontal="center")
    for i, s in enumerate(steps, start=1):
        ws.merge_cells(start_row=hr + i, start_column=1, end_row=hr + i, end_column=10)
        ws.cell(row=hr + i, column=1, value=s).alignment = Alignment(horizontal="right")
