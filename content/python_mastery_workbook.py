def split_tests(pools):
    """
    الهدف: تقسيم أسئلة كل وحدة: FINAL_PER_UNIT للاختبار الشامل (محجوزة)
    والبقية (حتى UNIT_TEST_SIZE) لاختبار إتقان الوحدة.
    """
    unit_tests, final = [], []
    for u in UNITS:
        pool = pools[u][:]
        RNG.shuffle(pool)
        final += pool[:FINAL_PER_UNIT]
        unit_tests += pool[FINAL_PER_UNIT:FINAL_PER_UNIT + UNIT_TEST_SIZE]
    RNG.shuffle(final)
    # ترقيم فريد لكل سؤال (يدخل في ترميز مفتاح الإجابة)
    for i, q in enumerate(unit_tests + final, start=1):
        q["id"] = i
    return unit_tests, final


def answer_index(q):
    """الهدف: رقم الإجابة الصحيحة 1..6 (أ،ب،ج،د،صح،خطأ)."""
    if q["options"] is None:
        return ANSWER_CODES.index(q["correct"]) + 1
    return q["options"].index(q["correct"]) + 1


def answer_code(q):
    """الهدف: الترميز المخزن في ورقة المفتاح (لا يكشف الحرف الصحيح مباشرة)."""
    return (q["id"] * 37 + answer_index(q) * 101) % 997


def answer_label(q):
    """الهدف: الإجابة الصريحة للمدرس، مثل «ب) len()»."""
    if q["options"] is None:
        return q["correct"]
    i = q["options"].index(q["correct"])
    return f"{LETTERS[i]}) {q['correct']}"


def options_text(q):
    """الهدف: نص الخيارات كما يظهر للطالب."""
    if q["options"] is None:
        return "صح\nخطأ"
    return "\n".join(f"{l}) {o}" for l, o in zip(LETTERS, q["options"]))


