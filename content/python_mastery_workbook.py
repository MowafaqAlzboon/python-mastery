def C(text):
    """الهدف: تنظيف كتل الكود متعددة الأسطر (إزالة المسافة البادئة المشتركة)."""
    return textwrap.dedent(text).strip("\n")


def unlock(cell):
    """الهدف: جعل الخلية قابلة للكتابة من الطالب رغم حماية الورقة وتلوينها بالأصفر."""
    cell.protection = Protection(locked=False)
    cell.fill = PatternFill("solid", fgColor=INPUT_FILL)


def protect(ws, allow_filter=True):
    """الهدف: حماية الورقة بكلمة مرور المدرس مع السماح بالتصفية والتحديد."""
    ws.protection.sheet = True
    ws.protection.password = INSTRUCTOR_PASSWORD
    ws.protection.autoFilter = not allow_filter   # False = مسموح
    ws.protection.selectLockedCells = False
    ws.protection.selectUnlockedCells = False


def add_lock_rule(ws, ref, formula):
    """
    الهدف: «إقفال مرئي»: عندما يكون الشرط صحيحاً يصبح لون النص مطابقاً للخلفية
    فيختفي المحتوى. يُستخدم لإخفاء الوحدات المقفلة والحلول والإجابات.
    """
    rule = FormulaRule(formula=[formula], stopIfTrue=True,
                       font=Font(color=LOCK_GRAY),
                       fill=PatternFill("solid", fgColor=LOCK_GRAY, bgColor=LOCK_GRAY))
    ws.conditional_formatting.add(ref, rule)


def build_sheet(wb, name, title, headers, data, widths, purpose,
                note_extra="", mandatory="إلزامي", allow_formulas=False,
                count_override=None, gate=None, register=True):
    """
    الهدف: الدالة الموحدة التي تبني أي ورقة بنفس البنية:
      1) صف ملاحظة أحمر (يتحول إلى رسالة إقفال إذا كانت الوحدة مقفلة)
      2) صف عنوان أزرق داكن  3) رؤوس أعمدة
      4) البيانات  5) حدود + التفاف + محاذاة علوية + تلوين متبادل
      6) عرض الأعمدة  7) تجميد الصفوف وتصفية تلقائية
      8) بوابة الإتقان (gate): اسم معرّف يساوي TRUE عندما تكون الوحدة مفتوحة
    """
    ws = wb.create_sheet(name)
    ws.sheet_view.rightToLeft = True
    ncol = len(headers)
    last_col = get_column_letter(ncol)

    # 1) صف الملاحظة العلوي (ديناميكي عند وجود بوابة)
    ws.merge_cells(f"A1:{last_col}1")
    note = (NOTE_TEXT + " " + note_extra).strip()
    if gate:
        locked_msg = "🔒 هذه الوحدة مقفلة: أتقن الوحدة السابقة في الورقة 14 أولاً، وتابع حالتك في الورقة 00."
        ws["A1"] = f'=IF({gate},"{note}","{locked_msg}")'
    else:
        ws["A1"] = note
    ws["A1"].font = Font(bold=True, color="FFFFFF", size=11)
    ws["A1"].fill = PatternFill("solid", fgColor=RED)
    ws["A1"].alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    ws.row_dimensions[1].height = 32

    # 2) صف العنوان الرئيسي
    ws.merge_cells(f"A2:{last_col}2")
    ws["A2"] = title
    ws["A2"].font = Font(bold=True, color="FFFFFF", size=14)
    ws["A2"].fill = PatternFill("solid", fgColor=DARK_BLUE)
    ws["A2"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 28

    # 3) رؤوس الأعمدة
    ws.append(headers)
    for cell in ws[3]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=LIGHT_BLUE)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER

    # 4) البيانات
    for row in data:
        if len(row) != ncol:
            raise ValueError(f"[{name}] صف بطول {len(row)} بدلاً من {ncol}: {row[:2]}")
        ws.append(list(row))

    # 5) تنسيق الخلايا + تلوين متبادل
    gray = PatternFill("solid", fgColor=LIGHT_GRAY)
    for r_idx, row in enumerate(ws.iter_rows(min_row=4, max_row=ws.max_row, max_col=ncol)):
        for cell in row:
            if (not allow_formulas and isinstance(cell.value, str)
                    and cell.value.startswith("=")):
                cell.data_type = "s"        # النص "==" يبقى نصاً لا معادلة
            cell.border = BORDER
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            if r_idx % 2 == 1:
                cell.fill = gray

    # 6) ضبط عرض الأعمدة
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    # 7) تجميد الصفوف وتصفية تلقائية
    ws.freeze_panes = "A4"
    ws.auto_filter.ref = f"A3:{last_col}{max(ws.max_row, 4)}"

    # 8) بوابة الإتقان: إخفاء المحتوى كاملاً عندما تكون الوحدة مقفلة
    if gate:
        add_lock_rule(ws, f"A4:{last_col}{max(ws.max_row, 4)}", f"NOT({gate})")

    if register:
        SHEET_REGISTRY.append({
            "name": name, "purpose": purpose, "mandatory": mandatory,
            "count": count_override if count_override is not None else len(data),
        })
    return ws



