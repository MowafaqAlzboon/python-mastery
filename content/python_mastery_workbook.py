TEST_HEADERS = ["رقم السؤال", "الوحدة", "المقرر", "نوع السؤال", "الصعوبة",
                "السؤال", "الخيارات", "إجابتك ✍", "النتيجة", "راجع عند الخطأ"]
TEST_WIDTHS = [8, 22, 7, 14, 9, 55, 38, 10, 9, 30]


def graded_sheet(wb, name, title, questions, key_col, purpose, note, lock_formula, reveal_formula):
    """
    الهدف: بناء ورقة اختبار مصححة آلياً:
      H = إجابة الطالب (قائمة منسدلة، الخلية الوحيدة القابلة للكتابة)
      K = عمود مخفي يحسب صحة الإجابة بمقارنة ترميزها بورقة المفتاح المخفية
      I = النتيجة ✓/✗ ولا تظهر إلا عند اكتمال الإجابة عن كل أسئلة الوحدة/الاختبار
    """
    rows = [[x["id"], x["unit"], x["course"], x["kind"], x["difficulty"], x["text"],
             options_text(x), None, None, x["ref"]] for x in questions]
    ws = build_sheet(wb, name, title, TEST_HEADERS, rows, TEST_WIDTHS, purpose, note,
                     mandatory="اختبار إلزامي", count_override=len(questions))
    last = ws.max_row
    dv_mcq = DataValidation(type="list", formula1='"أ,ب,ج,د"', allow_blank=True,
                            error="اختر أ أو ب أو ج أو د", showErrorMessage=True)
    dv_tf = DataValidation(type="list", formula1='"صح,خطأ"', allow_blank=True,
                           error="اختر صح أو خطأ", showErrorMessage=True)
    ws.add_data_validation(dv_mcq)
    ws.add_data_validation(dv_tf)
    for r, x in enumerate(questions, start=4):
        h = ws.cell(row=r, column=8)
        unlock(h)
        h.alignment = Alignment(horizontal="center", vertical="top")
        (dv_tf if x["options"] is None else dv_mcq).add(h.coordinate)
        k = ws.cell(row=r, column=11, value=(
            f'=IF(H{r}="",0,IF(IFERROR(MOD(A{r}*37+MATCH(H{r},{ANSWER_LIST},0)*101,997),-1)'
            f'={KEY_SHEET}!{key_col}{r},1,0))'))
        k.protection = HIDDEN_FORMULA
        res = ws.cell(row=r, column=9, value=(
            f'=IF(H{r}="","",IF({reveal_formula.format(r=r)},IF(K{r}=1,"✓","✗"),"⏳"))'))
        res.protection = HIDDEN_FORMULA
        res.alignment = Alignment(horizontal="center", vertical="top")
        res.font = Font(bold=True, size=12)
    ws.column_dimensions["K"].hidden = True
    add_lock_rule(ws, f"A4:J{last}", lock_formula)
    ws.conditional_formatting.add(f"I4:I{last}", FormulaRule(
        formula=['I4="✓"'], font=Font(bold=True, color="006100"),
        fill=PatternFill("solid", fgColor="C6EFCE", bgColor="C6EFCE")))
    ws.conditional_formatting.add(f"I4:I{last}", FormulaRule(
        formula=['I4="✗"'], font=Font(bold=True, color="9C0006"),
        fill=PatternFill("solid", fgColor="FFC7CE", bgColor="FFC7CE")))
    protect(ws)
    return ws


